-- Accounts carry their current balance plus an optimistic-lock version.
-- Balances are stored debit-positive in integer minor units of the account currency.
CREATE TABLE accounts (
    id                     UUID                     NOT NULL PRIMARY KEY,
    code                   VARCHAR(64)              NOT NULL,
    name                   VARCHAR(200)             NOT NULL,
    type                   VARCHAR(16)              NOT NULL,
    currency               VARCHAR(3)               NOT NULL,
    allow_negative_balance BOOLEAN                  NOT NULL DEFAULT FALSE,
    balance                BIGINT                   NOT NULL DEFAULT 0,
    version                BIGINT                   NOT NULL DEFAULT 0,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT accounts_code_uk UNIQUE (code),
    CONSTRAINT accounts_type_ck CHECK (type IN ('ASSET', 'LIABILITY', 'EQUITY', 'REVENUE', 'EXPENSE'))
);

CREATE TABLE journal_entries (
    id          UUID                     NOT NULL PRIMARY KEY,
    description VARCHAR(500),
    posted_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Postings are append-only. The identity column gives a per-database total order that statements page over;
-- balance_after records the account balance right after the posting was applied.
CREATE TABLE postings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id      UUID                     NOT NULL REFERENCES journal_entries (id),
    account_id    UUID                     NOT NULL REFERENCES accounts (id),
    currency      VARCHAR(3)               NOT NULL,
    amount        BIGINT                   NOT NULL,
    balance_after BIGINT                   NOT NULL,
    posted_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT postings_amount_ck CHECK (amount <> 0),
    CONSTRAINT postings_entry_account_uk UNIQUE (entry_id, account_id)
);

CREATE INDEX postings_account_seq_idx ON postings (account_id, id);
CREATE INDEX postings_account_time_idx ON postings (account_id, posted_at);
